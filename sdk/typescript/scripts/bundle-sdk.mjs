// Shared helper for vendoring @loom/sdk into the flue template.
//
// The flue runner template (internal/flue/template/.flue/workflows/runner.ts)
// imports the SDK to read its task via getTask() (PRD Phase B). A flue project
// is built/run with Vite and may be installed *inside a sandbox with no access
// to a private @loom/sdk registry entry*, so we vendor a single self-contained
// ESM bundle (openapi-fetch inlined, no node_modules dependency) the runner
// imports by relative path. esbuild output for a pinned version is stable, so a
// staleness gate (check-vendored-sdk.mjs) can diff it like the generated types.
import esbuild from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SDK_ROOT = join(here, ".."); // sdk/typescript
export const REPO_ROOT = join(SDK_ROOT, "..", ".."); // repo root
export const ENTRY = join(SDK_ROOT, "src", "index.ts");

/** Where the vendored copy lives inside the embedded flue template. */
export const VENDOR_DIR = join(
  REPO_ROOT,
  "internal",
  "flue",
  "template",
  ".flue",
  "vendor",
  "loom-sdk",
);
// Pair as index.js + index.d.ts (the template is "type":"module", so .js is
// ESM) — TS resolves the declaration for a `.js` import from the sibling
// `.d.ts`, which the `.mjs`/`.d.mts` pairing would not.
export const VENDOR_JS = join(VENDOR_DIR, "index.js");
export const VENDOR_DTS = join(VENDOR_DIR, "index.d.ts");

/** Value exports the bundle must expose (used by the staleness sanity check). */
export const EXPECTED_EXPORTS = [
  "BOOTSTRAP_ENV",
  "FencedError",
  "TaskRunClient",
  "TaskRunError",
  "bootstrapFromEnv",
];

const BANNER = [
  "// Code generated by @loom/sdk `npm run vendor` — DO NOT EDIT.",
  "// Self-contained ESM bundle of sdk/typescript/src (openapi-fetch inlined),",
  "// vendored so the flue runner template imports it with no node_modules dep",
  "// (it must build offline inside a sandbox). See",
  "// docs/product/loom-typescript-sdk-spec.md (Phase B).",
  "// Regenerate: cd sdk/typescript && npm run vendor. The check-vendored-sdk",
  "// gate (make check-sdk) fails CI if this drifts from the SDK source.",
].join("\n");

/** Bundle the SDK to a single self-contained ESM string (deterministic). */
export async function bundleSdk() {
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node22",
    write: false,
    minify: false,
    sourcemap: false,
    legalComments: "none",
    banner: { js: BANNER },
    logLevel: "silent",
  });
  return result.outputFiles[0].text;
}

/**
 * Hand-maintained `.d.ts` façade for the vendored bundle. The full generated
 * OpenAPI types are too large to vendor; the runner only needs the public
 * TaskRunClient surface plus the task fields it reads. The check gate verifies
 * the runtime bundle's exports; this façade keeps the import typed in the
 * template. Keep in sync with src/client.ts + src/bootstrap.ts.
 */
export const VENDOR_DTS_CONTENT = `// Code generated by @loom/sdk \`npm run vendor\` — DO NOT EDIT.
// Hand-maintained type façade for the vendored runtime bundle (index.mjs).
// Source of truth is sdk/typescript/src; see docs/product/loom-typescript-sdk-spec.md.

export interface TaskRunBootstrap {
  serverUrl: string;
  workspace: string;
  taskId: string;
  sessionId?: string;
  fencingToken?: string;
  token?: string;
  actor?: string;
}

export const BOOTSTRAP_ENV: {
  readonly serverUrl: "LOOM_SERVER_URL";
  readonly workspace: "LOOM_WORKSPACE";
  readonly taskId: "LOOM_TASK_ID";
  readonly taskIdFallback: "LOOM_ASSIGNED_TASK_ID";
  readonly sessionId: "LOOM_SESSION_ID";
  readonly fencingToken: "LOOM_FENCING_TOKEN";
  readonly token: "LOOM_TASKRUN_TOKEN";
  readonly actor: "LOOM_FLEET_DB_ACTOR";
};

export function bootstrapFromEnv(
  env?: Record<string, string | undefined>,
): TaskRunBootstrap;

/** A task as returned by the control plane (runner-relevant fields). */
export interface Task {
  id: string;
  title: string;
  description?: string;
  design?: string;
  acceptance_criteria?: string;
  status: string;
  issue_type: string;
  labels?: string[];
}

export interface ArtifactInput {
  type: "patch" | "commit" | "log" | "test" | string;
  uri: string;
  summary?: string;
  filesChanged?: number;
  idempotencyKey?: string;
}
export interface UsageInput {
  inputTokens: number;
  outputTokens: number;
  cacheReadTokens?: number;
  cacheWriteTokens?: number;
}
export interface LogInput {
  stream: "stdout" | "stderr";
  text: string;
}

export class TaskRunError extends Error {
  readonly op: string;
  readonly status: number | undefined;
  readonly body: unknown;
}
export class FencedError extends TaskRunError {}

export class TaskRunClient {
  readonly bootstrap: TaskRunBootstrap;
  static fromBootstrap(bootstrap: TaskRunBootstrap): TaskRunClient;
  static fromEnv(env?: Record<string, string | undefined>): TaskRunClient;
  getTask(): Promise<Task>;
  comment(text: string): Promise<void>;
  updateStatus(status: string): Promise<void>;
  complete(opts?: { reason?: string }): Promise<void>;
  postArtifact(artifact: ArtifactInput): Promise<void>;
  recordUsage(usage: UsageInput): Promise<void>;
  appendLog(log: LogInput): Promise<void>;
  heartbeat(): Promise<void>;
}
`;
