func TestRecorderOmitsCoverageWhenExecutableTestFails(t *testing.T) {
	t.Parallel()
	recorder := coverageRecorder{}
	failed := &recordingTest{name: "TestFailedScenario", failed: true}

	recorder.covers(failed, validScenario())
	failed.runCleanups()

	if scenarios := recorder.snapshot(); len(scenarios) != 0 {
		t.Fatalf("recorded failed scenarios = %d, want 0", len(scenarios))
	}
}

func TestRecorderGeneratesVersionedOwningReport(t *testing.T) {
	t.Parallel()
	recorder := coverageRecorder{}
	scenario := validScenario()
	scenario.Test = "TestExactRoundTrip"
	if err := recorder.record(scenario); err != nil {
		t.Fatal(err)
	}

	report, err := recorder.report("loom-sha")
	if err != nil {
		t.Fatal(err)
	}
	if report.SchemaVersion != SchemaVersion || report.Repository != RepositoryLoom || report.Revision != "loom-sha" {
		t.Fatalf("report identity = %#v", report)
	}
	if len(report.Cases) != 1 || report.Cases[0].ID != 1 || report.Cases[0].Test != "TestExactRoundTrip" {
		t.Fatalf("report cases = %#v", report.Cases)
	}

	var output bytes.Buffer
	if err := WriteYAML(&output, report); err != nil {
		t.Fatal(err)
	}
	written := output.String()
	for _, literal := range []string{
		"# Code generated by skills edge coverage; DO NOT EDIT.",
		"schema_version: skills-edge-coverage/v1",
		"repository: loom",
		"revision: loom-sha",
		"test: TestExactRoundTrip",
	} {
		if !strings.Contains(written, literal) {
			t.Fatalf("generated report omitted %q:\n%s", literal, written)
		}
	}
}

