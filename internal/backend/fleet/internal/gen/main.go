// Command gen generates Loom's test-only FleetDB action contract.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
)

const generatedFilename = "fleet_action_contract_generated_test.go"

type contractRow struct {
	Action             string
	EntityType         string
	ExpectedCoarseType string
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "generate FleetDB action contract: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	fleetDBFlag := flag.String("fleet-db", "", "FleetDB checkout (default: sibling of the Loom repo root)")
	outputFlag := flag.String("output", "", "generated Go output path")
	manifestFlag := flag.String("manifest", "", "producer manifest path (default: beside generated contract)")
	revisionFlag := flag.String("revision", "", "full FleetDB commit SHA, required with -update-producer")
	checkFlag := flag.Bool("check", false, "verify the committed contract against its pinned producer")
	upstreamFlag := flag.Bool("check-upstream", false, "compare selected FleetDB HEAD with the committed semantic contract")
	updateFlag := flag.Bool("update-producer", false, "explicitly update producer provenance and regenerate")
	printRevisionFlag := flag.Bool("print-producer-revision", false, "validate manifest and print its pinned producer revision")
	flag.Parse()

	repoRoot, err := findRepoRoot()
	if err != nil {
		return err
	}
	outputPath := *outputFlag
	if outputPath == "" {
		outputPath = filepath.Join(repoRoot, "internal", "backend", "fleet", generatedFilename)
	}
	if *printRevisionFlag {
		manifestPath := *manifestFlag
		if manifestPath == "" {
			manifestPath = filepath.Join(filepath.Dir(outputPath), producerFilename)
		}
		manifest, err := readProducer(manifestPath)
		if err != nil {
			return err
		}
		fmt.Println(manifest.Revision)
		return nil
	}
	fleetDBPath, err := resolveFleetDBPath(repoRoot, *fleetDBFlag)
	if err != nil {
		return err
	}
	return generateContract(generationOptions{
		fleetDB: fleetDBPath, output: outputPath, manifest: *manifestFlag,
		revision: *revisionFlag, check: *checkFlag, upstream: *upstreamFlag, update: *updateFlag,
	})
}

func renderContract(rows []contractRow) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintln(&buf, "// Code generated by the FleetDB action contract generator; DO NOT EDIT.")
	fmt.Fprintln(&buf, "// Producer provenance: fleet_action_contract_producer.json")
	fmt.Fprintln(&buf, "package fleet")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "type fleetActionContractRow struct {")
	fmt.Fprintln(&buf, "\tAction string")
	fmt.Fprintln(&buf, "\tEntityType string")
	fmt.Fprintln(&buf, "\tExpectedCoarseType string")
	fmt.Fprintln(&buf, "}")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "var fleetActionContract = []fleetActionContractRow{")
	for _, row := range rows {
		fmt.Fprintf(&buf, "\t{Action: %s, EntityType: %s, ExpectedCoarseType: %s},\n",
			strconv.Quote(row.Action), strconv.Quote(row.EntityType), strconv.Quote(row.ExpectedCoarseType))
	}
	fmt.Fprintln(&buf, "}")
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated contract: %w", err)
	}
	return formatted, nil
}

func expectedCoarseType(action, entityType string) string {
	switch action {
	case "issue.create":
		return "create"
	case "issue.delete":
		return "delete"
	case "issue.close", "issue.reopen":
		return "status"
	case "comment.add":
		return "comment"
	}
	if entityType == "workspace" {
		return "refresh"
	}
	return "update"
}
