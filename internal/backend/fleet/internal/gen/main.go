// Command gen generates Loom's test-only FleetDB action contract.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
)

const generatedFilename = "fleet_action_contract_generated_test.go"

type contractRow struct {
	Action             string
	EntityType         string
	ExpectedCoarseType string
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "generate FleetDB action contract: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	fleetDBFlag := flag.String("fleet-db", "", "FleetDB checkout (default: sibling of the Loom repo root)")
	outputFlag := flag.String("output", "", "generated Go output path")
	flag.Parse()

	repoRoot, err := findRepoRoot()
	if err != nil {
		return err
	}
	outputPath := *outputFlag
	if outputPath == "" {
		outputPath = filepath.Join(repoRoot, "internal", "backend", "fleet", generatedFilename)
	}
	fleetDBPath, err := resolveFleetDBPath(repoRoot, outputPath, *fleetDBFlag)
	if err != nil {
		return err
	}
	rows, err := parseFleetActionContract(filepath.Join(fleetDBPath, "internal", "models", "event.go"))
	if err != nil {
		return err
	}
	revision, err := gitRevision(fleetDBPath)
	if err != nil {
		return err
	}
	return writeContract(outputPath, revision, rows)
}

func writeContract(path, revision string, rows []contractRow) error {
	var buf bytes.Buffer
	fmt.Fprintln(&buf, "// Code generated by the FleetDB action contract generator; DO NOT EDIT.")
	fmt.Fprintf(&buf, "// FleetDB revision: %s\n\n", revision)
	fmt.Fprintln(&buf, "package fleet")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "type fleetActionContractRow struct {")
	fmt.Fprintln(&buf, "\tAction string")
	fmt.Fprintln(&buf, "\tEntityType string")
	fmt.Fprintln(&buf, "\tExpectedCoarseType string")
	fmt.Fprintln(&buf, "}")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "var fleetActionContract = []fleetActionContractRow{")
	for _, row := range rows {
		fmt.Fprintf(&buf, "\t{Action: %s, EntityType: %s, ExpectedCoarseType: %s},\n",
			strconv.Quote(row.Action), strconv.Quote(row.EntityType), strconv.Quote(row.ExpectedCoarseType))
	}
	fmt.Fprintln(&buf, "}")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format generated contract: %w", err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

func expectedCoarseType(action, entityType string) string {
	switch action {
	case "issue.create":
		return "create"
	case "issue.delete":
		return "delete"
	case "issue.close", "issue.reopen":
		return "status"
	case "comment.add":
		return "comment"
	}
	if entityType == "workspace" {
		return "refresh"
	}
	return "update"
}
