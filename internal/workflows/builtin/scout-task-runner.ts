// resolveBinary honors the LOOM_<BACKEND>_BIN override, else searches PATH.
export function resolveBinary(backend, env = process.env) {
  const override = stringValue(env["LOOM_" + backend.toUpperCase() + "_BIN"]);
  if (override) {
    if (override.includes(path.sep) || path.isAbsolute(override)) {
      return isExecutableFile(override) ? override : "";
    }
    const resolved = lookPath(override, env);
    return resolved || (isExecutableFile(override) ? override : "");
  }
  return lookPath(SUPPORTED[backend] || backend, env);
}

function lookPath(name, env) {
  if (name.includes(path.sep) || path.isAbsolute(name)) {
    return isExecutableFile(name) ? name : "";
  }
  const pathValue = stringValue(env.PATH || env.Path || "");
  for (const dir of pathValue.split(path.delimiter).filter(Boolean)) {
    const candidate = path.join(dir, name);
    if (isExecutableFile(candidate)) {
      return candidate;
    }
  }
  return "";
}

// backendArgs mirrors local-task-runner's non-interactive arg builders — the
// AGENTIC invocations with tool use allowed (ticket 03: the scout leaf reads
// files itself; the prototype's tool-less one-shot is the fallback shape, not
// the target). The workspace root is not a git repo, hence codex's
// --skip-git-repo-check.
export function backendArgs(backend, workspaceRoot, prompt) {
  switch (backend) {
    case "codex":
      return ["exec", "--json", "--skip-git-repo-check", "--dangerously-bypass-approvals-and-sandbox", "-"];
    case "claude": {
      const claudeArgs = ["-p", "--verbose", "--output-format", "stream-json", "--dangerously-skip-permissions"];
      const budget = resolveMaxBudgetUSD();
      if (budget) {
        claudeArgs.push("--max-budget-usd", budget);
      }
      const effort = resolveAgentEffort();
      if (effort) {
        claudeArgs.push("--effort", effort);
      }
      claudeArgs.push(prompt);
      return claudeArgs;
    }
    case "gemini":
      return ["--approval-mode=yolo", "-p", prompt, "-o", "stream-json"];
    case "opencode": {
      const opencodeArgs = ["run", "--format", "json", "--dir", workspaceRoot];
      const opencodeModel = stringValue(process.env.LOOM_OPENCODE_MODEL);
      if (opencodeModel) {
        opencodeArgs.push("--model", opencodeModel);
      }
      return opencodeArgs;
    }
    case "cursor":
      return ["-p", "--output-format", "stream-json", "--force", prompt];
    default:
      return [prompt];
  }
}

function backendUsesStdinPrompt(backend) {
  return backend === "opencode" || backend === "codex";
}

// DefaultMaxBudgetUSD / resolveMaxBudgetUSD / resolveAgentEffort mirror
// internal/cli/backends/backend_claude.go via local-task-runner.ts.
const DEFAULT_MAX_BUDGET_USD = 50.0;

function resolveMaxBudgetUSD() {
  const raw = stringValue(process.env.LOOM_MAX_BUDGET_USD);
  if (!raw) {
    return DEFAULT_MAX_BUDGET_USD.toFixed(2);
  }
  const value = Number(raw);
  if (!Number.isFinite(value) || value < 0) {
    return DEFAULT_MAX_BUDGET_USD.toFixed(2);
  }
  if (value === 0) {
    return ""; // explicit opt-out
  }
  return value.toFixed(2);
}

function resolveAgentEffort() {
  return stringValue(process.env.LOOM_AGENT_EFFORT) || stringValue(process.env.LOOM_CLAUDE_EFFORT);
}

async function execBackend(binary, args, options) {
  return await new Promise((resolve, reject) => {
    const child = execFile(
      binary,
      args,
      {
        cwd: options.cwd,
        // IS_SANDBOX=1 mirrors local-task-runner: claude-code refuses
        // --dangerously-skip-permissions under root without it; harmless for
        // the other backends.
        env: { ...(options.env || process.env), IS_SANDBOX: "1" },
        maxBuffer: 64 * 1024 * 1024,
        timeout: numberValue(process.env.LOOM_SCOUT_TASK_TIMEOUT_MS, 30 * 60 * 1000),
      },
      (error, stdout, stderr) => {
        if (error && typeof error.code !== "number" && !error.killed) {
          reject(error);
          return;
        }
        const code = error && typeof error.code === "number" ? error.code : error && error.killed ? 124 : 0;
        resolve({ code, stdout: String(stdout || ""), stderr: String(stderr || "") });
      },
    );
    // Always close stdin: stdin-prompt backends receive the prompt here,
    // positional-prompt backends get an immediate EOF so they never block.
    if (child.stdin) {
      if (options.input !== undefined) {
        child.stdin.end(options.input);
      } else {
        child.stdin.end();
      }
    }
  });
}

